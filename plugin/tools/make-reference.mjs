/**
 * Pulls the shaper functions and the presets straight out of fx/fracture.html
 * and writes them where the C++ tests can read them. The point is that the port
 * is checked against the ORIGINAL, not against a second copy of my own
 * arithmetic: if a formula was mistyped in C++, plugin/tests/test_core.cpp
 * fails on the very first mode.
 *
 *   node plugin/tools/make-reference.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = fs.readFileSync(path.join(root, 'fx', 'fracture.html'), 'utf8');

function grab(startMarker, endMarker) {
  const a = src.indexOf(startMarker);
  if (a < 0) throw new Error('cannot find ' + startMarker + ' in fx/fracture.html');
  const b = src.indexOf(endMarker, a);
  if (b < 0) throw new Error('cannot find the end of ' + startMarker);
  return src.slice(a + startMarker.length, b);
}

const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
const MODES = new Function('clamp', 'return [' + grab('const MODES = [', '\n];') + ']')(clamp);
const PRESETS = new Function('return [' + grab('const PRESETS = [', '\n];') + ']')();

if (MODES.length !== 14) throw new Error('expected 14 modes, found ' + MODES.length);

// x values that matter: the origin, small signal, both clip regions, well past
// full drive, and the half-steps where JavaScript's rounding differs from C's
const xs = [];
for (let x = -40; x <= 40; x += 0.125) xs.push(+x.toFixed(3));
for (const x of [-1.5, -0.5, -1 / 14, 0, 1 / 14, 0.5, 1.5, 3.5, 7.5, 0.0714285714285714]) xs.push(x);

const rows = ['mode,x,y'];
for (const m of MODES) {
  for (const x of xs) {
    const y = m.fn(x);
    if (!Number.isFinite(y)) throw new Error(`${m.id} is not finite at ${x}`);
    rows.push(`${m.id},${x},${y.toPrecision(17)}`);
  }
}
const outDir = path.join(root, 'plugin', 'tests');
fs.writeFileSync(path.join(outDir, 'shaper_reference.csv'), rows.join('\n') + '\n');
fs.writeFileSync(path.join(outDir, 'presets.json'), JSON.stringify(PRESETS, null, 1) + '\n');
console.log(`shaper_reference.csv — ${MODES.length} modes x ${xs.length} points`);
console.log(`presets.json — ${PRESETS.length} presets`);

// ---- core/Presets.h: the same nine patches, as JSON the plugin loads through
// the very same importer it offers users, so there is one code path for both
const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const lines = [
  '// Presets.h — GENERATED by plugin/tools/make-reference.mjs from the presets in',
  '// fx/fracture.html. Do not edit by hand; run `npm run reference` instead.',
  '//',
  '// They are stored as the browser\'s own patch JSON and loaded through the same',
  '// importer the "paste patch" button uses, so the factory presets and a patch',
  '// copied out of the web version cannot drift apart.',
  '#pragma once',
  '#include <vector>',
  '',
  'namespace fracture {',
  '',
  'struct Preset { const char* name; const char* json; };',
  '',
  'inline const std::vector<Preset>& presets(){',
  '    static const std::vector<Preset> all = {',
];
for (const p of PRESETS) {
  lines.push(`        { "${esc(p.name)}", R"JSON(${JSON.stringify(p.v)})JSON" },`);
}
lines.push('    };', '    return all;', '}', '', '} // namespace fracture', '');
fs.writeFileSync(path.join(root, 'plugin', 'core', 'Presets.h'), lines.join('\n'));
console.log(`core/Presets.h — ${PRESETS.length} presets`);
